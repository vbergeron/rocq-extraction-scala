package rocqextraction.core

import java.nio.file.Paths
import utest._

object ParsingTests extends TestSuite {
  val tests = Tests {
    test("dependencies") {
      val cwd = Paths.get("/w")
      // As printed by `rocq dep`, with a continuation line
      val output =
        "/w/r/Sub/Base.vo /w/r/Sub/Base.glob /w/r/Sub/Base.v.beautified /w/r/Sub/Base.required_vo: /w/r/Sub/Base.v /lib/rocqworker\n" +
          "r/Arith.vo r/Arith.glob r/Arith.v.beautified r/Arith.required_vo: r/Arith.v \\\n" +
          "  /w/r/Sub/Base.vo /lib/Corelib/Init/Prelude.vo\n"
      val base = Paths.get("/w/r/Sub/Base.v")
      val arith = Paths.get("/w/r/Arith.v")
      val graph = Dependencies.parse(output, Set(base, arith), cwd)
      assert(graph == Map(base -> Set.empty, arith -> Set(base)))
      assert(Dependencies.topologicalOrder(graph) == Seq(base, arith))
    }

    test("topologicalOrder") {
      val Seq(a, b, c, d) = Seq("a", "b", "c", "d").map(n => Paths.get(s"/$n.v"))
      val order = Dependencies.topologicalOrder(Map(a -> Set(c, b), b -> Set(d), c -> Set(d), d -> Set.empty))
      assert(order == Seq(d, b, c, a))
      val e = assertThrows[RocqException](Dependencies.topologicalOrder(Map(a -> Set(b), b -> Set(a))))
      assert(e.getMessage.contains("cycle"))
    }

    test("problems") {
      val output =
        """File "./src/Bad.v", line 3, characters 22-26:
          |Error:
          |The term "true" has type "bool"
          |while it is expected to have type "nat".
          |
          |File "/abs/Other.v", line 1, characters 0-5:
          |Warning: Notation "_ + _" was already used.
          |""".stripMargin
      val ps = Problems.parse(output, Paths.get("/w"))
      assert(
        ps == Seq(
          Problem(Paths.get("/w/src/Bad.v"), 3, 22, 26, Problem.Error,
            "The term \"true\" has type \"bool\"\nwhile it is expected to have type \"nat\"."),
          Problem(Paths.get("/abs/Other.v"), 1, 0, 5, Problem.Warning, "Notation \"_ + _\" was already used.")
        )
      )
    }

    test("driver") {
      val src = Driver.source(
        Seq(
          Extraction("Arith", "My.Arith", Seq("addNat", "mulNat")),
          Extraction("Other", "My.Other", Seq("f"), scalaPackage = Some("com.other"), pureFunctions = Some(true)),
          Extraction("Third", "My.Arith", Seq("g"))
        ),
        ExtractionOptions(Seq(Prelude.NatBigInt), Some("com.ex"), pureFunctions = false),
        Paths.get("/out/dir \"q\"")
      )
      val expected = Seq(
        "(* Generated by the Rocq extraction build plugin. Do not edit. *)",
        "From ScalaExtraction Require Import ScalaExtraction.",
        "From ScalaExtraction Require Import ExtrScalaNatBigInt.",
        "Require My.Arith.",
        "Require My.Other.",
        "Extraction Language Scala.",
        "Set Extraction Output Directory \"/out/dir \"\"q\"\"\".",
        "Set Extraction Scala Package \"com.ex\".",
        "Extraction \"Arith\" My.Arith.addNat My.Arith.mulNat.",
        "Set Extraction Scala Package \"com.other\".",
        "Set Extraction Scala Pure Functions.",
        "Extraction \"Other\" My.Other.f.",
        "Set Extraction Scala Package \"com.ex\".",
        "Unset Extraction Scala Pure Functions.",
        "Extraction \"Third\" My.Arith.g."
      ).map(_ + "\n").mkString
      assert(src == expected)
    }

    test("validation") {
      val ok = Extraction("Arith", "My.Arith", Seq("addNat", "n'"))
      assert(Validation.errors(Seq(ok), ExtractionOptions()) == Nil)
      val errs = Validation.errors(
        Seq(
          Extraction("bad-name", "My.Arith", Seq("f")),
          Extraction("A", "My Arith", Nil, scalaPackage = Some("1bad")),
          Extraction("B", "M", Seq("f")),
          Extraction("B", "M", Seq("g"))
        ),
        ExtractionOptions(scalaPackage = Some("com.ok"))
      )
      assert(
        errs == Seq(
          "extraction `bad-name`: the name must be a valid identifier, as it names the file and its object",
          "extraction `A`: `My Arith` is not a Rocq module path",
          "extraction `A`: no definitions to extract",
          "extraction `A`: Scala package `1bad` is not a dotted sequence of identifiers",
          "several extractions are named `B`"
        )
      )
    }
  }
}
