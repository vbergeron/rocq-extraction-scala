package rocqextraction.core

import java.nio.file.Path

/** The `.v` file that runs the declared extractions. */
object Driver {
  val fileName = "RocqExtractionDriver.v"

  private def string(s: String): String = "\"" + s.replace("\"", "\"\"") + "\""

  def source(extractions: Seq[Extraction], options: ExtractionOptions, outputDir: Path): String = {
    val b = new StringBuilder
    b ++= "(* Generated by the Rocq extraction build plugin. Do not edit. *)\n"
    b ++= "From ScalaExtraction Require Import ScalaExtraction.\n"
    options.preludes.distinct.foreach(p => b ++= s"From ScalaExtraction Require Import ${p.module}.\n")
    extractions.map(_.module).distinct.foreach(m => b ++= s"Require $m.\n")
    b ++= "Extraction Language Scala.\n"
    b ++= s"Set Extraction Output Directory ${string(outputDir.toString)}.\n"
    // Rocq's defaults: no package, no pure functions
    var pkg: Option[String] = None
    var pure = false
    extractions.foreach { e =>
      val wantedPkg = e.scalaPackage.orElse(options.scalaPackage)
      val wantedPure = e.pureFunctions.getOrElse(options.pureFunctions)
      if (wantedPkg != pkg) {
        b ++= wantedPkg.fold("Unset Extraction Scala Package.\n")(p => s"Set Extraction Scala Package ${string(p)}.\n")
        pkg = wantedPkg
      }
      if (wantedPure != pure) {
        b ++= (if (wantedPure) "Set" else "Unset") + " Extraction Scala Pure Functions.\n"
        pure = wantedPure
      }
      val names = e.definitions.map(d => s"${e.module}.$d")
      b ++= s"Extraction ${string(e.name)} ${names.mkString(" ")}.\n"
    }
    b.toString
  }
}
